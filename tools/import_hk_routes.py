"""Import only KML geometries and names; descriptions/links are reference data."""
import argparse
import hashlib
import json
import math
import sys
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NS = {"k": "http://www.opengis.net/kml/2.2"}
SPECS = [
    ("hk-island-mountain", "港島山道 → 赤柱", "HK / MOUNTAIN", "alpine", "告士打道", "赤柱峽道"),
    ("hk-aberdeen-tunnel", "香港仔隧道 → 赤柱", "HK / ABERDEEN", "coast", "告士打道", "赤柱峽道"),
    ("hk-kwun-tong", "觀塘繞道", "HK / KWUN TONG", "harbor", "鑽石山", "藍田"),
    ("hk-lung-cheung", "龍翔道・呈祥道", "HK / LUNG CHEUNG", "alpine", "蝴蝶谷", "彩虹"),
    ("hk-west-kowloon", "西九龍公路", "HK / WEST KOWLOON", "harbor", "荔景", "西九龍"),
    ("hk-island-east", "東區走廊", "HK / ISLAND EAST", "coast", "銅鑼灣", "筲箕灣"),
]

def distance(a, b):
    lat1, lat2 = math.radians(a[1]), math.radians(b[1])
    dlat, dlon = lat2-lat1, math.radians(b[0]-a[0])
    h = math.sin(dlat/2)**2 + math.cos(lat1)*math.cos(lat2)*math.sin(dlon/2)**2
    return 6371008.8 * 2 * math.atan2(math.sqrt(h), math.sqrt(1-h))

def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=ROOT / "sources/hk_driving_routes.kml")
    args = parser.parse_args()
    raw = args.input.read_bytes()
    document = ET.fromstring(raw)
    routes = []
    for place in document.findall(".//k:Placemark", NS):
        for line in place.findall(".//k:LineString", NS):
            coords = [[float(v) for v in token.split(",")] for token in line.findtext("k:coordinates", "", NS).split()]
            if len(coords)<2 or any(len(p)!=3 or not all(math.isfinite(v) for v in p) or not (113.8<p[0]<114.6 and 22<p[1]<22.7) for p in coords):
                raise ValueError("Invalid Hong Kong route coordinates")
            routes.append((place.findtext("k:name", "", NS), coords))
    if len(routes)!=len(SPECS):
        raise ValueError(f"Expected six supplied LineStrings, found {len(routes)}")
    output=[]
    for (source_name, coords), (route_id, name, label, theme, start, end) in zip(routes, SPECS):
        output.append(dict(id=route_id,name=name,label=label,tag=f"{start} → {end} · KML 點到點",theme=theme,cornerSpeed=24,
                           open=True,hongKong=True,startName=start,endName=end,sourceName=source_name,
                           sourcePoints=len(coords),coordinates=coords,origin=coords[0][:2],
                           sourcePolylineMetres=round(sum(distance(a,b) for a,b in zip(coords,coords[1:])),2),
                           accuracy="稀疏 KML 航點的遊戲化重建；未包含道路測繪高度"))
    provenance=dict(file="hk_driving_routes.kml",sha256=hashlib.sha256(raw).hexdigest(),coordinateSystem="WGS84 lon,lat,alt",altitudesAllZero=all(p[2]==0 for _,c in routes for p in c),routeCount=len(routes))
    (ROOT/"dist/hk-routes.mjs").write_text("// Generated by tools/import_hk_routes.py from the supplied KML.\nexport const HK_SOURCE="+json.dumps(provenance,ensure_ascii=False)+";\nexport const HK_COURSES="+json.dumps(output,ensure_ascii=False,separators=(",",":"))+";\n",encoding="utf-8")
    (ROOT/"qa/hk-kml-import.json").write_text(json.dumps(dict(status="PASS",source=provenance,routes=[{k:v for k,v in r.items() if k!="coordinates"} for r in output]),ensure_ascii=False,indent=2),encoding="utf-8")
    print(json.dumps({"status":"PASS","routes":[{"name":r["name"],"points":r["sourcePoints"],"polylineMetres":r["sourcePolylineMetres"]} for r in output]},ensure_ascii=False,indent=2))

if __name__=="__main__":
    main()
